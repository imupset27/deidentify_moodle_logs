# PURPOSE
#   Replace person identifiers in a raw Moodle log export with pseudonymous
#   codes so the log can be shared. Everything else is left unchanged:
#   timestamps, component, event names, and activity/quiz names (Event context).
#
# WHAT THIS SCRIPT CHANGES
#   1. "User full name" and "Affected user" -> user_id, affected_user_id
#        S<8 hex> = student/participant, T<8 hex> = staff/non-student account
#        Codes are HMAC-SHA256 of the name using a secret key, truncated to
#        8 hex characters. The same person always receives the same code.
#   2. Names found inside Description, Event context, and Origin are replaced
#      with the same codes (case-insensitive, whole-word match).
#   3. Moodle numeric user IDs in Description ("user with id '1234'") are
#      replaced with the person's code.
#   4. IPv4 addresses and e-mail addresses in Description are masked.
#   5. The "IP address" column is dropped.
#   6. Rows generated by staff/non-student accounts are removed when
#      drop_staff_rows = TRUE.
#
# WHAT THIS SCRIPT DOES NOT CHANGE
#   Time (exact timestamps retained), Component, Event name, Event context
#   (activity names), and all other columns.
#
# INPUT  (local only, NOT shared on OSF)
#   raw/<raw log CSV>        Moodle export: Site administration > Reports > Logs
#   .moodle_secret           One-line text file, random string, >= 20 chars.
#                            Create once, e.g.:
#                            writeLines(paste(sample(c(letters, LETTERS, 0:9),
#                                       40, TRUE), collapse = ""), ".moodle_secret")
#
# OUTPUT
#   data/logs_deidentified.csv         De-identified log (shareable)
#   data/deidentification_report.txt   Counts and checks only; contains no names
#   data/sessionInfo.txt               R and package versions
#
# REPRODUCIBILITY NOTE
#   Others cannot re-run this script because the raw data and the secret key
#   are not shared (privacy). The script is provided for transparency.
#   Anyone holding the raw data and the key can regenerate identical codes.
#
# DO NOT UPLOAD TO OSF OR GITHUB:
#   raw/ folder, .moodle_secret, any file listing real names.
#   Add these to .gitignore if using the OSF GitHub add-on.
#
# SOFTWARE
#   R >= 4.2; packages: readr, dplyr, stringr, digest, tibble
#   (exact versions are written to data/sessionInfo.txt)
# =============================================================================

library(readr)
library(dplyr)
library(stringr)
library(digest)
library(tibble)

# ---------------- 0. Working directory ----------------
# In RStudio, use the folder containing this (saved) script.
# With Rscript, the launch folder is used.
if (requireNamespace("rstudioapi", quietly = TRUE) && rstudioapi::isAvailable()) {
  setwd(dirname(rstudioapi::getSourceEditorContext()$path))
}
message("Working directory: ", getwd())

# ---------------- 1. Settings (edit) ----------------
raw_file    <- "raw/logs_MATHC505_20261110-1258.csv"
out_file    <- "data/logs_deidentified.csv"
report_file <- "data/deidentification_report.txt"
session_file <- "data/sessionInfo.txt"

# Non-student accounts (instructor, admin, dean, test accounts). Coded as T-codes.
# NOTE: if this script is published, these names are visible. Either list only
# generic labels, or read them from a private file, e.g.:
#   staff_names <- readLines("private/staff_names.txt")
staff_names <- c("Admin User", "Dr. Eduardo Lacap", "Dean GradSchool", "user user", "-")

drop_staff_rows <- TRUE   # TRUE = remove rows where the actor is a staff account

secret <- readLines(".moodle_secret", warn = FALSE)[1]
stopifnot(nchar(secret) >= 20)

# ---------------- 2. Read ----------------
# All columns are read as text so nothing (e.g., Time) is altered on import.
logs <- read_csv(raw_file, col_types = cols(.default = col_character()))
logs <- logs %>% mutate(across(everything(), ~ str_squish(.x)))
n_raw <- nrow(logs)

# ---------------- 3. Build name -> code map ----------------
people <- unique(c(logs$`User full name`, logs$`Affected user`))
people <- people[!is.na(people) & people != "-" & people != ""]

key <- tibble(name = people) %>%
  mutate(prefix  = if_else(name %in% staff_names, "T", "S"),
         pid     = paste0(prefix,
                          vapply(name, function(v) substr(hmac(secret, v, "sha256"), 1, 8),
                                 character(1), USE.NAMES = FALSE)),
         name_lc = str_to_lower(name)) %>%
  arrange(desc(nchar(name)))               # longest names first

stopifnot(!anyDuplicated(key$pid))         # collision check
lookup <- setNames(key$pid, key$name_lc)

if (drop_staff_rows) logs <- filter(logs, !`User full name` %in% staff_names)
n_after_staff <- nrow(logs)

# ---------------- 4. Map Moodle numeric IDs -> codes ----------------
# Description text looks like: "The user with id '1234' viewed ..."
id_map <- logs %>%
  mutate(uid = str_match(Description, "^The user with id '(\\d+)'")[, 2]) %>%
  filter(!is.na(uid)) %>%
  distinct(uid, name = `User full name`) %>%
  mutate(pid = unname(lookup[str_to_lower(name)]))

stopifnot(!anyDuplicated(id_map$uid))      # each ID must map to exactly one person
id_lookup <- setNames(id_map$pid, id_map$uid)

replace_user_ids <- function(x) {
  str_replace_all(x, "(user with id ')(\\d+)(')", function(m) {
    uid  <- str_match(m, "id '(\\d+)'")[, 2]
    code <- unname(id_lookup[uid])
    paste0("user with id '", ifelse(is.na(code), "UNKNOWN", code), "'")
  })
}

# ---------------- 5. Replace identity columns ----------------
logs <- logs %>%
  mutate(user_id          = unname(lookup[str_to_lower(`User full name`)]),
         affected_user_id = unname(lookup[str_to_lower(`Affected user`)]),
         .before = 1) %>%
  select(-`User full name`, -`Affected user`)

# ---------------- 6. Scrub names inside other text columns ----------------
# Time, Component, and Event name are skipped. Event context (quiz/activity
# names) is scanned for person names but otherwise left intact.
text_cols <- intersect(c("Description", "Event context", "Origin"), names(logs))
pattern   <- str_c("\\b(", str_c(str_escape(key$name), collapse = "|"), ")\\b")

for (col in text_cols) {
  logs[[col]] <- str_replace_all(logs[[col]], regex(pattern, ignore_case = TRUE),
                                 function(m) unname(lookup[str_to_lower(m)]))
}
logs$Description <- replace_user_ids(logs$Description)

# ---------------- 7. Remove other direct identifiers ----------------
logs <- logs %>%
  mutate(Description = str_replace_all(Description,
                                       "\\b\\d{1,3}(\\.\\d{1,3}){3}\\b", "[ip]"),
         Description = str_replace_all(Description,
                                       "[[:alnum:]._%+-]+@[[:alnum:].-]+\\.[A-Za-z]{2,}", "[email]")) %>%
  select(-any_of(c("IP address")))

# ---------------- 8. Safety checks ----------------
hits <- sum(str_detect(paste(logs$Description, logs$`Event context`),
                       regex(pattern, ignore_case = TRUE)), na.rm = TRUE)
left_ids <- sum(str_detect(logs$Description, "user with id '\\d+'"), na.rm = TRUE)
unknown  <- sum(str_detect(logs$Description, "UNKNOWN"), na.rm = TRUE)
no_user  <- sum(is.na(logs$user_id))

report <- c(
  "DE-IDENTIFICATION REPORT (no personal data)",
  paste("Run date             :", Sys.time()),
  paste("Rows in raw file     :", n_raw),
  paste("Rows after staff drop:", n_after_staff),
  paste("Rows in output       :", nrow(logs)),
  paste("Distinct user_id     :", n_distinct(logs$user_id)),
  paste("Name matches left    :", hits, "(should be 0)"),
  paste("Numeric IDs left     :", left_ids, "(should be 0)"),
  paste("UNKNOWN placeholders :", unknown),
  paste("Rows with no user_id :", no_user),
  paste("Time range kept      :", min(logs$Time, na.rm = TRUE), "to",
        max(logs$Time, na.rm = TRUE), "(as exported; not parsed)")
)
writeLines(report, con = stdout())

# ---------------- 9. Write outputs ----------------
dir.create(dirname(out_file), showWarnings = FALSE, recursive = TRUE)
write_csv(logs, out_file)
writeLines(report, report_file)
capture.output(sessionInfo(), file = session_file)
message("Done. Wrote: ", out_file)
